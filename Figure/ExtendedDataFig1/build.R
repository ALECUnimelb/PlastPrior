#!/usr/bin/env Rscript
source('Figure/_shared/managed.R')
library(dplyr)
for(f in c('data.R','plot_sankey.R','plot_upset.R','assemble.R')) source(file.path(module_dir,f))
compounds <- read_current(c('Inchikey_std','keep_for_vega','qc_flags'))
catalog <- readr::read_csv(file.path(output_dir,'source_data/source_catalog.csv'),show_col_types=FALSE)
attrition <- readr::read_csv(file.path(output_dir,'source_data/source_attrition.csv'),show_col_types=FALSE)
sankey <- prepare_sankey_source_data(NULL,compounds,catalog,attrition,config)
overlap <- prepare_database_overlap(NULL,compounds,catalog,attrition,config)
sankey_panel <- plot_identity_resolution_flow(sankey$edges,sankey$nodes,config)
upset <- plot_source_database_intersections(overlap,config)
save_nested(sankey,'flow/'); save_nested(overlap[vapply(overlap,is.data.frame,logical(1))],'overlap/')
for(name in setdiff(names(sankey_panel),'plot')) if(is.data.frame(sankey_panel[[name]])) save_table(sankey_panel[[name]],paste0('layout/',name))
checks <- c('label_collisions','label_node_collisions','connector_intersections','connector_node_collisions','connector_label_collisions','connector_orthogonality','connector_clearance_violations','order_violations')
for(name in checks) if(nrow(sankey_panel[[name]])>0) stop('Sankey layout failed: ',name)
save_table(upset$matrix_data,'layout/upset_matrix');save_table(upset$connector_data,'layout/upset_connectors')
save_facts(list(flow=sankey$summary,overlap=overlap$summary,source_definition='Distinct full InChIKey and source-table membership, derived from retained record links; FCChumon S1/S2 remain separate.',missing='Source membership is an observed record relation, not imputed scoring evidence.'))
save_plot(assemble_source_assembly_and_overlap(sankey_panel$plot,upset$plot),183,218)
