#!/usr/bin/env Rscript
source('Figure/_shared/current.R')
source(file.path(module_dir,'panels/hazard_dimension_overlap/plot.R'))
source(file.path(module_dir,'panels/exposure_dimension_overlap/plot.R'))
source(file.path(module_dir,'assemble.R'))
fields <- c('Inchikey_std',unname(hazard_score_columns),unique(unlist(exposure_score_columns)))
compounds <- read_current(fields)
for(f in setdiff(fields,'Inchikey_std')) compounds[[f]] <- strict_numeric(compounds[[f]],f)
complete_exposure <- read_current(c('Inchikey_std',unique(unlist(exposure_score_columns))),'exposure')
for(f in setdiff(names(complete_exposure),'Inchikey_std')) complete_exposure[[f]] <- strict_numeric(complete_exposure[[f]],f,FALSE)
hazard <- prepare_hazard_overlap(compounds,file.path(output_dir,'source_data/hazard'))
exposure <- prepare_exposure_overlap(complete_exposure,file.path(output_dir,'source_data/exposure'))
save_table(data.frame(Inchikey_std=compounds$Inchikey_std,exposure_complete=compounds$Inchikey_std %in% complete_exposure$Inchikey_std),'exposure_population')
save_facts(list(hazard=hazard$statistics,exposure=exposure$statistics,full_inventory=nrow(compounds),exposure_complete=nrow(complete_exposure),exposure_incomplete=nrow(compounds)-nrow(complete_exposure),missing='Hazard sets mean usable evidence including supported zero; exact positive exposure patterns use the complete-exposure pool. Incomplete exposure records are reported separately, not classified as negative.'))
save_plot(assemble_evidence_overlap_patterns(hazard$plot,exposure$plot),183,220)
