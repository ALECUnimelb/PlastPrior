#!/usr/bin/env Rscript
source('Figure/_shared/current.R')
sensitivity_dir <- file.path(figures_dir,'Fig4')
config <- configure_current(jsonlite::fromJSON(file.path(sensitivity_dir,'figure.yml'),simplifyVector=FALSE))
source(file.path(sensitivity_dir,'style.R'));source(file.path(sensitivity_dir,'data.R'));source(file.path(sensitivity_dir,'assemble.R'))
ids <- c('positive_input_breadth','positive_input_prevalence')
for(id in ids) source(file.path(sensitivity_dir,'panels',id,'plot.R'))
input <- read_priority_sensitivity_input(list(row_count=as.integer(lock$ranked)),config)
prepared <- prepare_priority_sensitivity_data(input,config,include_sensitivity=FALSE)
plots <- list(positive_input_breadth=plot_priority_positive_input_breadth(prepared$source_data$positive_input_breadth,config),positive_input_prevalence=plot_priority_positive_input_prevalence(prepared$source_data$positive_input_prevalence,config))
save_nested(prepared$source_data);save_nested(prepared$audit_tables)
save_facts(c(prepared$statistics,list(full_inventory=lock$total,breadth=prepared$source_data$positive_input_breadth$positive_input_breadth_metrics,missing='Full rankable population including partial evidence; positive means an available score greater than zero, not evidence completeness.')))
save_plot(assemble_priority_positive_input_context(plots,config),183,76)
